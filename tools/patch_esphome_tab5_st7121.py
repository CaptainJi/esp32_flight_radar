def main() -> int:
    spec = importlib.util.find_spec("esphome.components.mipi_dsi.models.m5stack")
    if spec is None or not spec.origin:
        print("esphome mipi_dsi models not found; is esphome installed?", file=sys.stderr)
        return 1
    path = Path(spec.origin)
    text = path.read_text(encoding="utf-8")
    if MARKER in text:
        print(f"already patched: {path}")
        return 0
    if not text.rstrip().endswith(")"):
        print(f"unexpected end of file, abort: {path}", file=sys.stderr)
        return 1
    path.write_text(text.rstrip() + "\n" + PATCH.lstrip("\n"), encoding="utf-8")
    print(f"patched: {path}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
